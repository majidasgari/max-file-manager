export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = lang === 'fa' ? key : (EN[key] ?? key)
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

/** True when a translation exists, used by tests and by the coverage report. */
