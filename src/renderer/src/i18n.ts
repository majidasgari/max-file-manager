/**
 * Two languages, one catalogue: the Persian string is the key, so a missing translation falls back
 * to Persian instead of showing a raw key. English is the default.
 */
export type Lang = 'en' | 'fa'

let lang: Lang = 'en'

/** React subscribes through `useSyncExternalStore`; changing the module value alone repaints nothing. */
const listeners = new Set<() => void>()

export const setLang = (l: Lang): void => {
  const next: Lang = l === 'fa' ? 'fa' : 'en'
  const changed = next !== lang
  lang = next
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr'
    document.title = lang === 'fa' ? 'مدیر فایل مکس' : 'Max File Manager'
  }
  if (changed) for (const fn of listeners) fn()
}
export const getLang = (): Lang => lang

export const subscribeLang = (fn: () => void): (() => void) => {
  listeners.add(fn)
  return () => {
    listeners.delete(fn)
  }
}

